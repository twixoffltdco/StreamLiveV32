-- Различаем ДВЕ разные причины suspended=1 у задеплоенных сервисов:
--   'system'    — автостоп по 30-дневной неактивности владельца (можно снять автоматически,
--                 как только владелец снова зайдёт на платформу)
--   'moderator' — ручная блокировка за нарушение (снимать можно ТОЛЬКО руками из модераторки,
--                 иначе возврат владельца на сайт случайно разморозит то, что заблокировали за дело)
-- Раньше suspended_by не было вообще, и функции "снять автостоп" тоже не было — сервис,
-- один раз остановленный по неактивности, оставался остановленным навсегда, даже если
-- владелец возвращался и активно пользовался платформой.

ALTER TABLE deployed_services ADD COLUMN suspended_by ENUM('system','moderator') DEFAULT NULL;
